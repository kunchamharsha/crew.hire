from django.db import models

class User(models.Model):
    id = models.BigAutoField(primary_key=True, max_length=60)
    username = models.CharField(unique=True, max_length=60, blank=True, null=True)
    firstname = models.CharField(max_length=100, blank=True, null=True)
    fullname = models.CharField(max_length=200, blank=True, null=True)
    lastname = models.CharField(max_length=100, blank=True, null=True)
    email = models.CharField(max_length=60, blank=True, null=True)
    phone_number = models.CharField(max_length=15, blank=True, null=True)
    fb_id = models.CharField(max_length=60, blank=True, null=True)
    gender = models.CharField(max_length=10, blank=True, null=True)
    dob = models.CharField(max_length=20, blank=True, null=True)
    bio = models.CharField(max_length=500, blank=True, null=True)
    image_url = models.CharField(max_length=200, blank=True, null=True)
    is_verified = models.BooleanField(default=False)
    audited = models.BooleanField(default=False)
    is_blocked = models.IntegerField(blank=True, null=True)
    create_time = models.DateTimeField(blank=True, null=True, auto_now_add=True, auto_now=False)
    update_time = models.DateTimeField(blank=True, null=True, auto_now=True)
    firebase_registration_token = models.CharField(max_length=200, blank=True, null=True)
    badge_url = models.CharField(max_length=200, blank=True, null=True)
    is_wallet_enable = models.BooleanField(default=False)
    referral_enable = models.BooleanField(default=False)
    is_adult = models.BooleanField(default=False)
    type = models.CharField(max_length=20, blank=True, null=True)
    login_type = models.CharField(max_length=50, blank=True, null=True)
    role = models.CharField(max_length=60, blank=True, null=True)
    language = models.CharField(max_length=50, blank=True, null=False)
    location = models.CharField(max_length=100, blank=True, null=False)
    conver_image_url = models.CharField(max_length=200, blank=True, null=True)
    insta_url = models.CharField(max_length=200, blank=True, null=True)
    fb_url = models.CharField(max_length=200, blank=True, null=True)
    password = models.CharField(max_length=200)
    description = models.TextField()
